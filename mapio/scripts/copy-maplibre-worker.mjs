// Copies MapLibre's self-contained worker module to /public so it is served as-is.
// MapLibre v6 resolves its worker relative to import.meta.url, which bundlers rewrite.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const pkg = require("maplibre-gl/package.json");
const src = path.join(path.dirname(require.resolve("maplibre-gl/package.json")), "dist", "maplibre-gl-worker.mjs");
const dest = path.join(process.cwd(), "public", "vendor", `maplibre-gl-worker-${pkg.version}.mjs`);
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.copyFileSync(src, dest);
fs.writeFileSync(path.join(process.cwd(), "src", "lib", "map", "worker-version.ts"), `// generated by scripts/copy-maplibre-worker.mjs\nexport const MAPLIBRE_WORKER_URL = "/vendor/maplibre-gl-worker-${pkg.version}.mjs";\n`);
console.log("maplibre worker →", path.relative(process.cwd(), dest));
